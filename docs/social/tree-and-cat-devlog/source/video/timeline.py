def get_total_duration():
    return round(sum(s["duration"] for s in SCENES), 4)


def get_scene_ranges():
    out = []
    t = 0.0
    for idx, s in enumerate(SCENES):
        start = round(t, 4)
        end = round(t + s["duration"], 4)
        out.append((idx, start, end, s))
        t = end
    return out
