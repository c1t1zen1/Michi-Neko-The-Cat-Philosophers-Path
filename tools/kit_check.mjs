// Static kit checks (Node, fast). Run from the repo root:
//
//   node tools/kit_check.mjs
//
// Checks (BUILD_GUIDE_FABLE F1.5 + Integrator rulings):
//   - src/kit/index.js is in sync with the family folders (tools/kit_index.mjs)
//   - every src/kit/<family>/index.js exports `assets`
//   - every defineAsset id is an inventory id (labs/asset_inventory.json) and unique across the kit
//   - no kit file imports from labs/
//   - no Math.random, Date.now, performance.now or this.random in kit builders (code, not comments)
//   - param defaults inside their ranges (one-line schema entries, statically; defineAsset re-checks at load)
//   - every relative import inside src/kit/** carries the cache tag of src/main.js
//   - the core modules exist and src/kit/budgets.js cites budgets.md (its status is reported)
import { readdirSync, readFileSync, existsSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateIndex, indexInSync, familyFolders, currentTag } from './kit_index.mjs';

// --root <dir> checks another tree with the same layout (the unit tests point
// it at fixture trees to prove every rule can fail).
const rootArg = process.argv.indexOf('--root');
const ROOT = rootArg > 0 && process.argv[rootArg + 1] ? process.argv[rootArg + 1] : join(fileURLToPath(new URL('.', import.meta.url)), '..');
const KIT = join(ROOT, 'src', 'kit');

let failed = 0, passed = 0;
const ok = (m) => { passed++; console.log('OK   ' + m); };
const bad = (m) => { failed++; console.log('FAIL ' + m); };
const note = (m) => console.log('NOTE ' + m);
const strip = (s) => (s.charCodeAt(0) === 0xFEFF ? s.slice(1) : s);
const rel = (p) => relative(ROOT, p).split('\\').join('/');

const walk = (dir) => readdirSync(dir).flatMap((f) => {
  const p = join(dir, f);
  return statSync(p).isDirectory() ? walk(p) : p.endsWith('.js') ? [p] : [];
});

/**
 * Source with comments blanked and, unless `keepStrings`, string literals
 * emptied too (so a comment or a GLSL string never trips a rule). The id
 * scan keeps strings; the forbidden-call scan drops them.
 */
export function codeOnly(src, { keepStrings = false } = {}) {
  let out = '', i = 0;
  const n = src.length;
  while (i < n) {
    const c = src[i], d = src[i + 1];
    if (c === '/' && d === '/') { while (i < n && src[i] !== '\n') i++; continue; }
    if (c === '/' && d === '*') { const e = src.indexOf('*/', i + 2); i = e < 0 ? n : e + 2; out += ' '; continue; }
    if (c === '\'' || c === '"' || c === '`') {
      const q = c, start = i; i++;
      while (i < n && src[i] !== q) { if (src[i] === '\\') i++; i++; }
      i++; out += keepStrings ? src.slice(start, i) : q + q; continue;
    }
    out += c; i++;
  }
  return out;
}

// --- core files -------------------------------------------------------------
for (const f of ['runtime.js', 'contract.js', 'materials.js', 'craft.js', 'rng.js', 'index.js', 'budgets.js']) {
  if (existsSync(join(KIT, f))) ok(`src/kit/${f} present`); else bad(`src/kit/${f} missing`);
}

// --- generated index ------------------------------------------------------------
const families = familyFolders(KIT);
if (indexInSync(ROOT)) ok(`src/kit/index.js in sync (${families.length} families${families.length ? ': ' + families.join(', ') : ''})`);
else bad('src/kit/index.js out of date — run: node tools/kit_index.mjs');
const indexText = existsSync(join(KIT, 'index.js')) ? readFileSync(join(KIT, 'index.js'), 'utf8') : '';
if (/GENERATED by tools\/kit_index\.mjs/.test(indexText)) ok('src/kit/index.js carries the GENERATED banner');
else bad('src/kit/index.js must be generated by tools/kit_index.mjs');
for (const name of readdirSync(KIT).filter((f) => statSync(join(KIT, f)).isDirectory())) {
  if (!families.includes(name)) bad(`src/kit/${name}/ has no index.js (every family folder exports \`assets\` from index.js)`);
}

// --- families export assets -----------------------------------------------------
for (const family of families) {
  const text = strip(readFileSync(join(KIT, family, 'index.js'), 'utf8'));
  if (/export\s+(?:const|let|var)\s+assets\b/.test(text) || /export\s*\{[^}]*\bassets\b[^}]*\}/.test(text)) ok(`family ${family}: index.js exports assets`);
  else bad(`family ${family}: index.js must export \`assets\``);
}

// --- ids: inventory + unique ---------------------------------------------------
const inventory = JSON.parse(strip(readFileSync(join(ROOT, 'labs', 'asset_inventory.json'), 'utf8')));
const inventoryIds = new Map(inventory.assets.map((a) => [a.id, a]));
const files = existsSync(KIT) ? walk(KIT) : [];
const familyFiles = files.filter((f) => rel(f).split('/').length > 3); // src/kit/<family>/...
const seen = new Map();
const DEFINE = /defineAsset\s*\(\s*\{[\s\S]*?\bid\s*:\s*(['"])([^'"]+)\1/g;
for (const f of familyFiles) {
  const text = codeOnly(strip(readFileSync(f, 'utf8')), { keepStrings: true });
  for (const m of text.matchAll(DEFINE)) {
    const id = m[2];
    const row = inventoryIds.get(id);
    if (!row) bad(`${rel(f)}: defineAsset id '${id}' is not in labs/asset_inventory.json`);
    else if (row.lifecycle && row.lifecycle !== 'active') bad(`${rel(f)}: defineAsset id '${id}' is ${row.lifecycle} in the inventory`);
    else ok(`${rel(f)}: id '${id}' is an active inventory id`);
    if (seen.has(id)) bad(`id '${id}' defined twice: ${seen.get(id)} and ${rel(f)}`);
    seen.set(id, rel(f));
  }
}
ok(`${seen.size} kit asset id(s) across ${families.length} family folder(s)`);

// --- forbidden imports and calls ------------------------------------------------
const IMPORT = /(?:from\s*|import\s*\(\s*)(['"])([^'"]+)\1/g;
const tag = currentTag(ROOT);
for (const f of files) {
  const raw = strip(readFileSync(f, 'utf8'));
  const code = codeOnly(raw);
  const imports = [...raw.matchAll(IMPORT)].map((m) => m[2]);
  for (const spec of imports) {
    if (/(^|\/)labs\//.test(spec)) bad(`${rel(f)}: imports from labs/ (${spec}) — promote the code into src/kit/`);
  }
  // runtime.js is the orchestrator (it times builds with performance.now);
  // every other kit file is geometry/material code and must be deterministic.
  if (rel(f) !== 'src/kit/runtime.js') {
    for (const [name, re] of [['Math.random', /\bMath\s*\.\s*random\b/], ['Date.now', /\bDate\s*\.\s*now\b/], ['performance.now', /\bperformance\s*\.\s*now\b/], ['this.random', /\bthis\s*\.\s*random\b/], ['this.rng()', /\bthis\s*\.\s*rng\s*\(/]]) {
      if (re.test(code)) bad(`${rel(f)}: uses ${name} — kit geometry must draw from ctx.rng`);
    }
  }
  // relative imports carry the current cache tag; bare specifiers (three) do not need one
  for (const spec of imports) {
    if (!spec.startsWith('.')) continue;
    const t = (spec.match(/\?v=([0-9a-z]+)$/) || [])[1];
    if (t === tag) ok(`${rel(f)}: ${spec} carries tag ${tag}`);
    else bad(`${rel(f)}: ${spec} must carry ?v=${tag} (the tag in src/main.js)`);
  }
}

// --- param defaults inside ranges (one-line entries) ---------------------------------
const NUM_LINE = /^\s*([a-z_][a-z0-9_]*)\s*:\s*\{[^}]*type\s*:\s*['"]number['"][^}]*\}/;
const ENUM_LINE = /^\s*([a-z_][a-z0-9_]*)\s*:\s*\{[^}]*type\s*:\s*['"]enum['"][^}]*\}/;
const field = (line, name) => { const m = line.match(new RegExp(`\\b${name}\\s*:\\s*(-?[0-9.]+)`)); return m ? Number(m[1]) : null; };
let paramLines = 0;
for (const f of familyFiles) {
  const lines = strip(readFileSync(f, 'utf8')).split(/\r?\n/);
  lines.forEach((line, i) => {
    const where = `${rel(f)}:${i + 1}`;
    let m = line.match(NUM_LINE);
    if (m) {
      paramLines++;
      const d = field(line, 'default'), lo = field(line, 'min'), hi = field(line, 'max');
      if (d === null || lo === null || hi === null) bad(`${where}: number param '${m[1]}' needs default, min and max`);
      else if (lo > hi) bad(`${where}: param '${m[1]}' min > max`);
      else if (d < lo || d > hi) bad(`${where}: param '${m[1]}' default ${d} outside [${lo}, ${hi}]`);
      return;
    }
    m = line.match(ENUM_LINE);
    if (m) {
      paramLines++;
      const d = (line.match(/\bdefault\s*:\s*['"]([^'"]*)['"]/) || [])[1];
      const opts = (line.match(/\boptions\s*:\s*\[([^\]]*)\]/) || [])[1];
      if (d === undefined || opts === undefined) bad(`${where}: enum param '${m[1]}' needs default and options`);
      else if (!opts.split(',').map((s) => s.trim().replace(/^['"]|['"]$/g, '')).includes(d)) bad(`${where}: enum param '${m[1]}' default '${d}' is not in options`);
    }
  });
}
ok(`${paramLines} one-line param schema entries checked statically (defineAsset validates all of them at load)`);

// --- budgets ------------------------------------------------------------------
const budgets = existsSync(join(KIT, 'budgets.js')) ? strip(readFileSync(join(KIT, 'budgets.js'), 'utf8')) : '';
if (/docs\/fable\/baseline\/budgets\.md/.test(budgets)) ok('src/kit/budgets.js cites docs/fable/baseline/budgets.md');
else bad('src/kit/budgets.js must cite docs/fable/baseline/budgets.md');
const status = (budgets.match(/status\s*:\s*['"]([a-z]+)['"]/) || [])[1];
if (status === 'accepted') ok('budgets: accepted (D1)');
else if (existsSync(join(ROOT, 'docs', 'fable', 'baseline', 'budgets.md'))) note(`budgets.js is ${status || 'unmarked'} but docs/fable/baseline/budgets.md exists — copy the accepted numbers in and set status: 'accepted'`);
else note(`budgets.js is ${status || 'unmarked'}; docs/fable/baseline/budgets.md has not landed yet`);

// --- the runtime keeps the frozen names -----------------------------------------
const runtime = strip(readFileSync(join(KIT, 'runtime.js'), 'utf8'));
const contract = strip(readFileSync(join(KIT, 'contract.js'), 'utf8'));
for (const [name, re, src] of [
  ['AssetRuntime exported', /export class AssetRuntime\b/, runtime],
  ['CLASSIC_ASSETS exported', /export const CLASSIC_ASSETS\b/, runtime],
  ['isAssetInstance exported', /export \{ isAssetInstance \}/, runtime],
  ['build(id, layout, classicFn)', /\bbuild\(id, layout, classicFn\)/, runtime],
  ['defineAsset exported', /export function defineAsset\b/, contract],
  ['ctx fields frozen', /\['THREE', 'MAT', 'kitMaterials', 'tier', 'rng', 'quality', 'textures'\]/, runtime],
  ['part names asset:<id>/<part>', /\$\{NAME_PREFIX\}\$\{id\}\/\$\{part\}/, contract]
]) {
  if (re.test(src)) ok('contract: ' + name); else bad('contract: ' + name + ' (frozen name changed?)');
}

console.log(failed ? `\n${failed} kit check(s) failed (${passed} passed)` : `\nAll kit checks OK (${passed} passed)`);
process.exit(failed ? 1 : 0);
